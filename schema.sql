-- Required extension for UUID generation
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ─────────────────────────────────────────────────────────────
-- 1. WORKSPACES
--    One row per VS Code workspace window.
--    "path" is the absolute fs path of the workspace root.
--    Scoping all other data through workspace_id ensures
--    complete isolation between windows.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS workspaces (
    id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    path         TEXT        NOT NULL,
    name         TEXT        NOT NULL,
    github_user  TEXT        NOT NULL DEFAULT 'aryasentry',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT workspaces_path_unique UNIQUE (path)
);

COMMENT ON TABLE  workspaces         IS 'One row per VS Code workspace root. Isolated by absolute path.';
COMMENT ON COLUMN workspaces.path    IS 'Absolute filesystem path, normalised to forward slashes, lowercase.';
COMMENT ON COLUMN workspaces.name    IS 'Human-readable display name — last path segment.';

-- ─────────────────────────────────────────────────────────────
-- 2. TASKS
--    The active "ticket" or goal a developer is working on.
--    Only ONE task can be active per workspace at a time,
--    enforced by the partial unique index below.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS tasks (
    id             UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id   UUID        NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    task_key       TEXT        NOT NULL,
    description    TEXT        NOT NULL,
    github_user    TEXT        NOT NULL DEFAULT 'aryasentry',
    is_active      BOOLEAN     NOT NULL DEFAULT true,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    deactivated_at TIMESTAMPTZ,

    CONSTRAINT tasks_workspace_key_unique UNIQUE (workspace_id, task_key)
);

-- Only one ACTIVE task per workspace at any time
CREATE UNIQUE INDEX IF NOT EXISTS tasks_one_active_per_workspace_idx
    ON tasks (workspace_id)
    WHERE is_active = true;

COMMENT ON TABLE  tasks              IS 'Developer tasks/tickets. One active per workspace.';
COMMENT ON COLUMN tasks.task_key    IS 'Short identifier, e.g. FEAT-001. Must be unique per workspace.';
COMMENT ON COLUMN tasks.is_active   IS 'Only one row with is_active=true per workspace_id (enforced by partial index).';

-- ─────────────────────────────────────────────────────────────
-- 3. FILE_CHANGES
--    One row per batch-processing cycle per file.
--    Captures the raw diff and metadata.
--    file_path is stored RELATIVE to the workspace root.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS file_changes (
    id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id  UUID        NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    task_id       UUID        REFERENCES tasks(id) ON DELETE SET NULL,
    github_user   TEXT        NOT NULL DEFAULT 'aryasentry',
    file_path     TEXT        NOT NULL,
    file_hash     TEXT        NOT NULL,
    diff_content  TEXT,
    change_cycle  INTEGER     NOT NULL DEFAULT 1,
    is_new_file   BOOLEAN     NOT NULL DEFAULT false,
    processed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS file_changes_workspace_idx    ON file_changes (workspace_id);
CREATE INDEX IF NOT EXISTS file_changes_task_idx         ON file_changes (task_id);
CREATE INDEX IF NOT EXISTS file_changes_processed_at_idx ON file_changes (processed_at DESC);
CREATE INDEX IF NOT EXISTS file_changes_file_path_idx    ON file_changes (workspace_id, file_path);

COMMENT ON TABLE  file_changes               IS 'One row per batch processing cycle per file.';
COMMENT ON COLUMN file_changes.file_path     IS 'Path relative to workspace root, forward slashes.';
COMMENT ON COLUMN file_changes.diff_content  IS 'Unified diff. NULL for binary files or read errors.';
COMMENT ON COLUMN file_changes.change_cycle  IS 'Monotonically increasing per file within a workspace.';

-- ─────────────────────────────────────────────────────────────
-- 4. CHANGE_DESCRIPTIONS
--    LLM-generated description of each file change.
--    Generated by Ollama (qwen3-vl:235b-cloud) via the
--    description server. One row per successful Ollama call.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS change_descriptions (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    file_change_id  UUID        NOT NULL REFERENCES file_changes(id) ON DELETE CASCADE,
    workspace_id    UUID        NOT NULL REFERENCES workspaces(id)   ON DELETE CASCADE,
    task_id         UUID        REFERENCES tasks(id) ON DELETE SET NULL,
    github_user     TEXT        NOT NULL DEFAULT 'aryasentry',
    model           TEXT        NOT NULL DEFAULT 'qwen3-vl:235b-cloud',
    summary         TEXT        NOT NULL,
    classification  TEXT        NOT NULL
        CHECK (classification IN (
            'feature', 'bugfix', 'refactor', 'test', 'docs',
            'chore', 'style', 'perf', 'security', 'unknown'
        )),
    on_task_score   FLOAT       NOT NULL
        CHECK (on_task_score BETWEEN 0.0 AND 1.0),
    raw_response    JSONB,
    latency_ms      INTEGER,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS change_descriptions_file_change_idx ON change_descriptions (file_change_id);
CREATE INDEX IF NOT EXISTS change_descriptions_workspace_idx   ON change_descriptions (workspace_id);
CREATE INDEX IF NOT EXISTS change_descriptions_created_at_idx  ON change_descriptions (created_at DESC);

COMMENT ON TABLE  change_descriptions                  IS 'Ollama-generated descriptions for each file change.';
COMMENT ON COLUMN change_descriptions.on_task_score    IS '0=completely off-task, 1=perfectly aligned with active task.';
COMMENT ON COLUMN change_descriptions.classification   IS 'Best-fit change type label chosen by the LLM.';

-- ─────────────────────────────────────────────────────────────
-- 5. ALIGNMENT_SNAPSHOTS
--    Rolling history of overall alignment state.
--    One row written per batch processing cycle.
--    Used for the score ring in the sidebar and future charts.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS alignment_snapshots (
    id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id  UUID        NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    task_id       UUID        REFERENCES tasks(id) ON DELETE SET NULL,
    github_user   TEXT        NOT NULL DEFAULT 'aryasentry',
    score         FLOAT       NOT NULL
        CHECK (score BETWEEN 0.0 AND 1.0),
    state         TEXT        NOT NULL
        CHECK (state IN ('aligned', 'mild-drift', 'drift', 'idle', 'paused', 'no-task')),
    files_changed INTEGER     NOT NULL DEFAULT 0,
    computed_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS alignment_snapshots_workspace_idx   ON alignment_snapshots (workspace_id);
CREATE INDEX IF NOT EXISTS alignment_snapshots_computed_at_idx ON alignment_snapshots (computed_at DESC);

COMMENT ON TABLE  alignment_snapshots             IS 'Time-series of alignment scores per workspace.';
COMMENT ON COLUMN alignment_snapshots.score       IS 'Aggregate cosine similarity for this batch.';
COMMENT ON COLUMN alignment_snapshots.state       IS 'Derived state label from the score thresholds.';
COMMENT ON COLUMN alignment_snapshots.files_changed IS 'Number of distinct files in the triggering batch.';

