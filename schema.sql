CREATE INDEX IF NOT EXISTS change_chunks_workspace_idx ON change_chunks (workspace_id);
CREATE INDEX IF NOT EXISTS change_chunks_task_idx      ON change_chunks (task_id);
CREATE INDEX IF NOT EXISTS change_chunks_end_time_idx  ON change_chunks (end_time DESC);

COMMENT ON TABLE change_chunks IS 'Time-based chunk summaries for history search.';

