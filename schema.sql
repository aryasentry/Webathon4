-- 7. HELPER VIEWS
-- ─────────────────────────────────────────────────────────────

-- Latest active task per workspace
CREATE OR REPLACE VIEW active_tasks AS
SELECT
    w.path       AS workspace_path,
    w.name       AS workspace_name,
    t.id         AS task_id,
    t.task_key,
    t.description,
    t.created_at
FROM workspaces w
JOIN tasks t ON t.workspace_id = w.id AND t.is_active = true;

COMMENT ON VIEW active_tasks IS 'Convenience view: currently active task per workspace.';

-- Recent descriptions with context (last 100 per workspace)
CREATE OR REPLACE VIEW recent_descriptions AS
SELECT
    cd.id,
    cd.workspace_id,
    cd.task_id,
    fc.file_path,
    fc.change_cycle,
    cd.summary,
    cd.classification,
    cd.on_task_score,
    cd.model,
    cd.latency_ms,
    cd.created_at
FROM change_descriptions cd
JOIN file_changes fc ON fc.id = cd.file_change_id
ORDER BY cd.created_at DESC;

COMMENT ON VIEW recent_descriptions IS 'Last LLM descriptions with file context, newest first.';

-- ─────────────────────────────────────────────────────────────
-- 8. chunks_pending_embedding VIEW
--    Queried by faiss-service/supabase_sync.py to find all
--    sealed chunks that haven't been embedded yet. Using a view
--    keeps the Python code simple and decoupled from the table name.
-- ─────────────────────────────────────────────────────────────
DROP VIEW IF EXISTS chunks_pending_embedding;
CREATE VIEW chunks_pending_embedding AS
SELECT
    id           AS chunk_id,
    workspace_id,
    task_id,
    github_user,
    summary,
    file_paths,
    start_time,
    end_time,
    created_at
FROM change_chunks
WHERE is_embedded = false
ORDER BY created_at ASC;

COMMENT ON VIEW chunks_pending_embedding IS 'Unembedded chunks, consumed by the FAISS sync service.';


