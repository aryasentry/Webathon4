-- ─────────────────────────────────────────────────────────────
-- SHARED TRIGGER FUNCTION
-- Sets updated_at = now() before any UPDATE.
-- Used by all ugie_ tables that track mutations.
-- ─────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION ugie_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

