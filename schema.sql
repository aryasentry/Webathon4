-- ============================================================
-- CROSS-SCHEMA VIEW: developer_activity
-- Joins CodePolice alignment data with ugie commit/repo context.
-- Useful for dashboards: "show all activity for user X in repo Y".
-- ============================================================
CREATE OR REPLACE VIEW developer_activity AS
SELECT
    gi.github_login,
    gi.avatar_url,
    r.full_name          AS repo_full_name,
    w.path               AS workspace_path,
    cd.summary,
    cd.classification,
    cd.on_task_score,
    t.task_key,
    t.description        AS task_description,
    fc.file_path,
    fc.processed_at
FROM change_descriptions cd
JOIN file_changes        fc ON fc.id             = cd.file_change_id
JOIN workspaces          w  ON w.id              = cd.workspace_id
LEFT JOIN tasks          t  ON t.id              = cd.task_id
LEFT JOIN ugie_github_identities gi ON gi.id     = cd.github_identity_id
LEFT JOIN ugie_repositories      r  ON r.id      = w.repo_id
ORDER BY fc.processed_at DESC;

COMMENT ON VIEW developer_activity IS 'Cross-schema view: CodePolice change data enriched with ugie GitHub identity and repo context.';


